#!/usr/bin/env python3
"""Convert `terraform show -json <plan>` output into a Sentinel tfplan/v2 mock.

  terraform show -json plan.tfplan | python3 plan_to_mock.py > mock-tfplan-v2.sentinel

Sentinel map/list literals look like JSON but need a trailing comma before each
newline, so values are written with a small custom serializer. resource_changes
is keyed by resource address, as in tfplan/v2.
"""

import json
import sys



def sentinel(v, indent=0):
    """Serialize a JSON value as a Sentinel literal."""
    pad, inner = "  " * indent, "  " * (indent + 1)
    if isinstance(v, dict):
        if not v:
            return "{}"
        items = "".join(f"{inner}{json.dumps(k)}: {sentinel(v[k], indent + 1)},\n" for k in sorted(v))
        return "{\n" + items + pad + "}"
    if isinstance(v, list):
        if not v:
            return "[]"
        return "[\n" + "".join(f"{inner}{sentinel(x, indent + 1)},\n" for x in v) + pad + "]"
    return json.dumps(v)  # strings, numbers, true/false/null are valid Sentinel


plan = json.load(sys.stdin)

resource_changes = {}
for rc in plan.get("resource_changes", []):
    resource_changes[rc["address"]] = {
        "address": rc["address"],
        "module_address": rc.get("module_address", ""),
        "mode": rc["mode"],
        "type": rc["type"],
        "name": rc["name"],
        "index": rc.get("index"),
        "provider_name": rc["provider_name"],
        "deposed": rc.get("deposed", ""),
        "change": {
            "actions": rc["change"]["actions"],
            "before": rc["change"].get("before"),
            "after": rc["change"].get("after"),
            "after_unknown": rc["change"].get("after_unknown", {}),
        },
    }

variables = {k: {"name": k, "value": v.get("value")} for k, v in plan.get("variables", {}).items()}

out = sys.stdout
out.write("# Generated by infra/scripts/plan_to_mock.py - do not edit by hand.\n\n")
out.write(f'terraform_version = {json.dumps(plan.get("terraform_version", ""))}\n\n')
out.write(f"variables = {sentinel(variables)}\n\n")
out.write(f"resource_changes = {sentinel(resource_changes)}\n\n")
out.write("output_changes = {}\n")
